"""Build phase14/DATA_MANIFEST.json (every file, size, sha256, rows, decoding settings) and the
inventory section of phase14/DATA_CATALOG.md. Re-run after every sync; nothing is regenerated.

    python paper/scripts/phase14_catalog.py            # hashes everything (hidden arrays: a few minutes)
    python paper/scripts/phase14_catalog.py --fast     # hidden arrays: size only
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
MIRROR = ROOT / "outputs/phase14_remote/outputs/phase14_v1"
HIDDEN = Path("F:/AGI_data/phase14_hidden")
OUT_JSON = ROOT / "phase14/DATA_MANIFEST.json"
OUT_MD = ROOT / "phase14/DATA_CATALOG.md"
MARK = "<!-- INVENTORY: generated by paper/scripts/phase14_catalog.py; do not edit below -->"
GROUPS = {
    "text_outputs": (MIRROR, ("*/*/*/*/answers.jsonl", "*/*/*/*/summary.json", "*/*/*/*/audit.jsonl")),
    "analysis": (MIRROR / "main/analysis", ("*",)),
    "smoke": (MIRROR / "smoke", ("*.json",)),
    "hidden_summaries": (MIRROR / "hidden", ("*/*/*/*.json",)),
    "logs": (ROOT / "outputs/phase14_remote/logs", ("*",)),
    "paper_results": (ROOT / "paper/results", ("phase14_*",)),
    "frozen_sources": (ROOT / "phase14/data", ("sources_v1/*", "raw/manifest.json", "main_size.json",
                                                "gsm8k13_audit_excluded.json", "execution_lock_*.json")),
}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 24), b""):
            h.update(chunk)
    return h.hexdigest()


def entry(path: Path, base: Path, do_hash: bool = True) -> dict:
    e = {"path": path.relative_to(base).as_posix(), "bytes": path.stat().st_size}
    if do_hash:
        e["sha256"] = sha256(path)
    if path.suffix == ".jsonl":
        with open(path, "rb") as f:
            e["rows"] = sum(1 for line in f if line.strip())
    return e


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fast", action="store_true", help="do not hash hidden-state arrays")
    args = parser.parse_args()
    manifest = {"schema_version": "phase14_data_manifest_v1", "built": time.strftime("%Y-%m-%d %H:%M (local)"),
                "roots": {"mirror": str(MIRROR), "hidden": str(HIDDEN), "repo": str(ROOT)}, "groups": {}, "stages": []}
    for name, (base, patterns) in GROUPS.items():
        files = sorted({p for pat in patterns for p in base.glob(pat) if p.is_file()})
        manifest["groups"][name] = {"base": str(base), "files": [entry(p, base) for p in files]}
    hidden_files = sorted(HIDDEN.glob("*/*/*/*.npz")) if HIDDEN.exists() else []
    manifest["groups"]["hidden_arrays"] = {"base": str(HIDDEN),
                                           "files": [entry(p, HIDDEN, not args.fast) for p in hidden_files]}
    for summ in sorted(MIRROR.glob("*/*/*/*/summary.json")):
        stage_dir = summ.parent
        split, model, dataset, stage = stage_dir.relative_to(MIRROR).parts
        s = json.loads(summ.read_text(encoding="utf-8"))
        st = s.get("settings", {})
        manifest["stages"].append({
            "split": split, "model": model, "dataset": dataset, "stage": stage, "rows": s.get("rows"),
            "answers_sha256_lf": s.get("answers_sha256"), "imported_from": s.get("imported_from"),
            "repo": st.get("model"), "revision": st.get("revision"), "temperature": st.get("temperature"),
            "top_p": st.get("top_p"), "max_new_tokens": st.get("max_new_tokens"), "batch_size": st.get("batch_size"),
            "logprobs": st.get("logprobs"), "gpu": st.get("gpu")})
    OUT_JSON.write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8", newline="\n")

    lines = [MARK, "", f"## 6. Kiểm kê (sinh tự động {manifest['built']})", ""]
    for name, g in manifest["groups"].items():
        lines.append(f"- **{name}** (`{g['base']}`): {len(g['files'])} file, "
                     f"{sum(f['bytes'] for f in g['files']) / 2**30:.2f} GB")
    lines += ["", "### Mỗi stage sinh dữ liệu (split / mô hình / dataset)", "",
              "| Split | Mô hình | Dataset | Stage | Dòng | Revision | temperature | max tokens | batch | GPU | sha256 answers (LF) |",
              "|---|---|---|---|---:|---|---:|---:|---:|---|---|"]
    for s in manifest["stages"]:
        rev = (s["revision"] or "")[:8] if not s["imported_from"] else f"nhập từ `{s['imported_from']}`"
        lines.append(f"| {s['split']} | {s['model']} | {s['dataset']} | {s['stage']} | {s['rows']} | {rev} | "
                     f"{s['temperature']} | {s['max_new_tokens']} | {s['batch_size']} | {s['gpu'] or '—'} | "
                     f"`{(s['answers_sha256_lf'] or '')[:12]}…` |")
    lines += ["", "### Hidden state (F:)", "", "| File | GB | sha256 |", "|---|---:|---|"]
    for f in manifest["groups"]["hidden_arrays"]["files"]:
        lines.append(f"| `{f['path']}` | {f['bytes'] / 2**30:.2f} | `{f.get('sha256', 'chưa băm (--fast)')[:16]}…` |")
    text = OUT_MD.read_text(encoding="utf-8") if OUT_MD.exists() else ""
    head = text.split(MARK)[0].rstrip() + "\n\n" if MARK in text else text
    OUT_MD.write_text(head + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_JSON} and the inventory of {OUT_MD}: {len(manifest['stages'])} stages, "
          f"{len(hidden_files)} hidden arrays")


if __name__ == "__main__":
    main()
